import type { ThrottlerOptions } from '@nestjs/throttler';

const MINUTE_MS = 60_000;

/**
 * Предел обращений с одного адреса.
 *
 * Виджет обращается сюда из браузера посетителя: открытие страницы стоит
 * двух запросов, а поиск врача добавляет по одному на каждую паузу в
 * наборе. Предел рассчитан на такую работу, а не на выгрузку всей ленты.
 *
 * Отсчет ведется по адресу посетителя, а не по кабинету: иначе крупный
 * клиент вытеснял бы остальных из общего счета.
 */
export const DEFAULT_THROTTLE: ThrottlerOptions = { ttl: MINUTE_MS, limit: 120 };
