import { IsInt, IsOptional, Max, Min } from 'class-validator';

/** Границы шкалы оценок агрегатора. */
const MIN_RATING = 1;
const MAX_RATING = 5;

/**
 * Изменение условий вывода отзывов.
 *
 * Каждое поле необязательно: переданное изменяется, отсутствующее остается
 * прежним. Консоль меняет одно условие, не пересылая остальные, а появление
 * нового условия не затрагивает запросы, которые о нем не знают.
 */
export class UpdateReviewFilterDto {
  /**
   * Наименьшая выводимая оценка; null снимает ограничение.
   *
   * IsOptional пропускает без проверки и отсутствующее значение, и null.
   * Их различает служба: отсутствие поля оставляет условие прежним, null
   * его снимает.
   */
  @IsOptional()
  @IsInt({ message: 'Оценка должна быть целым числом' })
  @Min(MIN_RATING, { message: `Оценка должна быть не меньше ${MIN_RATING}` })
  @Max(MAX_RATING, { message: `Оценка должна быть не больше ${MAX_RATING}` })
  minRating?: number | null;
}
