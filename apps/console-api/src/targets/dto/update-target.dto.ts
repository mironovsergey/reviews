import { IsBoolean } from 'class-validator';

/**
 * Изменение клиники или врача из консоли.
 *
 * Поле одно и обязательно: прочие данные цели приходят от агрегатора и
 * перезаписываются синхронизацией, а флагом вывода распоряжается кабинет.
 */
export class UpdateTargetDto {
  /** Выводится ли цель в виджете. */
  @IsBoolean({ message: 'Признак вывода должен быть логическим значением' })
  isActive: boolean;
}
