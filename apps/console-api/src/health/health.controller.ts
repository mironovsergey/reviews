import { Controller, Get } from '@nestjs/common';
import { SkipThrottle } from '@nestjs/throttler';

/** Ответ проверки работоспособности. */
export interface HealthResponseDto {
  status: 'ok';
}

/**
 * Признак живого процесса для HEALTHCHECK контейнера.
 *
 * Состояние базы намеренно не проверяется. Отрицательный ответ приводит к
 * перезапуску контейнера, а перезапуск не восстанавливает недоступную базу:
 * служба лишь потеряет установленное соединение и разорвет обработку
 * запросов, которые еще могли быть выполнены. Проверяется ровно то, что
 * перезапуск способен починить, - способность процесса отвечать.
 *
 * Путь выведен из-под ограничения частоты: проверка обращается сюда по
 * расписанию и не должна соперничать за общий счет с запросами клиентов.
 */
@Controller('health')
@SkipThrottle()
export class HealthController {
  @Get()
  check(): HealthResponseDto {
    return { status: 'ok' };
  }
}
